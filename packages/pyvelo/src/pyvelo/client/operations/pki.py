from __future__ import annotations

from collections.abc import Sequence
from typing import TYPE_CHECKING, Protocol

from pyvelo.client.operations._tagging import EDGE, SECURITY, SYSTEM, domain_tag
from pyvelo.client.schemas.pki import (
    EdgeCsrResult,
    GatewayCsrResult,
    GatewayPendingCsrResult,
    GetCurrentRevokedCertificates,
    GetEdgeCsr,
    GetEdgePendingCsrs,
    GetGatewayCsr,
    GetGatewayPendingCsrs,
    PendingCsrResult,
    RenewEdgeCertificate,
    RenewEdgeCertificateResult,
    RevokedCertificatesResult,
)

if TYPE_CHECKING:
    from pyvelo.client._client_protocol import VcoClientBaseProtocol


class PkiMixin(Protocol):
    """Operations for pki/ API endpoints."""

    @domain_tag(SECURITY)
    async def get_current_revoked_certificates(
        self: VcoClientBaseProtocol, request: GetCurrentRevokedCertificates
    ) -> RevokedCertificatesResult:
        """Get currently revoked edge and gateway PKI certificates.

        Returns the list of certificates that have been revoked for edges and gateways. In the
        VeloCloud PKI infrastructure, certificates are used to authenticate edges and gateways
        to the orchestrator and to establish secure VCMP tunnels. Certificates may be revoked
        when a device is decommissioned, compromised, or re-provisioned. Optionally filters to
        certificates revoked after a given date for incremental indexing. Useful for security
        auditing and maintaining certificate revocation awareness.

        Returns:
            Object with revokedEdges and revokedGateways arrays containing revoked certificate
            records with certificate identity, revocation date, reason, and device information
        """
        return await self.portal(
            "pki/getCurrentRevokedCertificates",
            request,
            RevokedCertificatesResult,
        )

    @domain_tag(SECURITY, EDGE)
    async def get_edge_csr(
        self: VcoClientBaseProtocol, request: GetEdgeCsr
    ) -> EdgeCsrResult:
        """Get the most recently recorded Certificate Signing Request (CSR) for an edge.

        Returns the latest CSR generated by the specified edge. In the VeloCloud PKI system,
        edges generate CSRs when they need new certificates for authenticating to the orchestrator
        and establishing secure overlay tunnels. The CSR contains the edge's public key and
        identity information and must be signed by the enterprise's certificate authority.
        Useful for PKI management, certificate renewal workflows, and troubleshooting
        authentication issues.

        Returns:
            Edge CSR object with CSR data (PEM format), creation time, and signing status
        """
        return await self.portal("pki/getEdgeCSR", request, EdgeCsrResult)

    @domain_tag(SECURITY, EDGE)
    async def get_edge_pending_csrs(
        self: VcoClientBaseProtocol, request: GetEdgePendingCsrs
    ) -> Sequence[PendingCsrResult]:
        """Get all edge CSRs that do not yet have an associated signed certificate.

        Returns all pending (unsigned) Certificate Signing Requests for edges. A pending CSR
        indicates that an edge has requested a new certificate but the CSR has not yet been
        signed by the certificate authority. Pending CSRs require action to complete the
        certificate enrollment process. Useful for identifying edges that need certificate
        provisioning and monitoring PKI enrollment status.

        Returns:
            Array of pending CSR objects with CSR data, edge identity, creation time,
            and enrollment status
        """
        return await self.portal_list(
            "pki/getEdgePendingCSRs", request, PendingCsrResult
        )

    @domain_tag(SECURITY, EDGE)
    async def renew_edge_certificate(
        self: VcoClientBaseProtocol, request: RenewEdgeCertificate
    ) -> RenewEdgeCertificateResult:
        """Renew the PKI certificate for a specific edge.

        Triggers certificate renewal for the specified edge. This initiates a new
        certificate signing request and certificate issuance workflow on the VCO.
        Use this when an edge certificate is approaching expiration or has expired.
        The edge must be in a connected state for the renewal to take effect.

        Returns:
            Renewal result confirming the operation
        """
        return await self.portal(
            "pki/renewEdgeCertificate", request, RenewEdgeCertificateResult
        )

    @domain_tag(SECURITY, SYSTEM)
    async def get_gateway_csr(
        self: VcoClientBaseProtocol, request: GetGatewayCsr
    ) -> GatewayCsrResult:
        """Get the most recently recorded Certificate Signing Request (CSR) for a gateway.

        Returns the latest CSR generated by the specified gateway. Gateways use certificates
        for authenticating to the orchestrator and establishing secure tunnels with edges.
        The CSR contains the gateway's public key and identity information. Useful for
        gateway PKI management and certificate renewal workflows.

        Returns:
            Gateway CSR object with CSR data (PEM format), creation time, and signing status
        """
        return await self.portal("pki/getGatewayCSR", request, GatewayCsrResult)

    @domain_tag(SECURITY, SYSTEM)
    async def get_gateway_pending_csrs(
        self: VcoClientBaseProtocol, request: GetGatewayPendingCsrs
    ) -> Sequence[GatewayPendingCsrResult]:
        """Get all gateway CSRs that do not yet have an associated signed certificate.

        Returns all pending (unsigned) Certificate Signing Requests for gateways across the
        VCO. A pending CSR indicates that a gateway has requested a new certificate but the
        CSR has not yet been signed by the certificate authority. Useful for identifying
        gateways that need certificate provisioning and monitoring PKI enrollment status
        at the infrastructure level.

        Returns:
            Array of pending gateway CSR objects with CSR data, gateway identity,
            creation time, and enrollment status
        """
        return await self.portal_list(
            "pki/getGatewayPendingCSRs", request, GatewayPendingCsrResult
        )
