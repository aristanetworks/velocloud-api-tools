import matplotlib
import polars as pl

matplotlib.use("Agg")

import matplotlib.pyplot as plt
from matplotlib.axes import Axes
from matplotlib.dates import DateFormatter
from matplotlib.figure import Figure
from matplotlib.ticker import FuncFormatter
from pyvelo.analytics import Analytics, FlowGroupBy, FlowMetric
from pyvelo.client import VcoClient
from pyvelo.client.enums import EdgeState
from pyvelo.client.schemas.enterprise import GetEnterprise, GetEnterpriseEdges
from pyvelo.core import ApiInterval

from pyvelo_examples.common import get_vco_credentials

logger = logging.getLogger(__name__)


@dataclass
class AnalyticsReportArgs:
    env: str | None = None
    enterprise_id: int | None = None
    hours: int = 1
    edge_name: str | None = None
    output: str = "analytics_report.html"
    verbose: bool = False


def parse_args(argv: Sequence[str] | None = None) -> AnalyticsReportArgs:
    parser = argparse.ArgumentParser(
        description="Generate an HTML report with analytics time-series charts.",
    )
    _ = parser.add_argument("--env", type=str, help="Path to .env file")
    _ = parser.add_argument(
        "--enterprise-id",
        type=int,
        help="Enterprise ID (auto-discovered from token if omitted)",
    )
    _ = parser.add_argument(
        "--hours",
        type=int,
        help="Lookback window in hours (default: 1)",
    )
    _ = parser.add_argument(
        "--edge-name",
        type=str,
        help="Filter to edges matching this substring",
    )
    _ = parser.add_argument(
        "--output",
        type=str,
        help="Output HTML file path (default: analytics_report.html)",
    )
    _ = parser.add_argument("--verbose", "-v", action="store_true", help="Debug logging")
    return parser.parse_args(argv, namespace=AnalyticsReportArgs())


def make_interval(hours: int) -> ApiInterval:
    now = datetime.now(tz=UTC)
    return ApiInterval(start=now - timedelta(hours=hours))


def svg_from_figure(fig: Figure) -> str:
    buf = io.BytesIO()
    fig.savefig(buf, format="svg", bbox_inches="tight")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib leaves file-like kwargs open-ended.
    plt.close(fig)
    svg = buf.getvalue().decode("utf-8")
    idx = svg.find("<svg")
    if idx > 0:
        svg = svg[idx:]
    return svg


def build_html(sections: list[tuple[str, str]], title: str) -> str:
    parts = [
        "<!DOCTYPE html>",
        "<html><head>",
        "<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; script-src 'none'; style-src 'unsafe-inline'\">",
        f"<title>{escape(title)}</title>",
        "<style>",
        (
            "body { font-family: system-ui, sans-serif; max-width: 1200px; "
            "margin: 0 auto; padding: 2rem; background: #fafafa; }"
        ),
        "h1 { border-bottom: 2px solid #333; padding-bottom: 0.5rem; }",
        "h2 { margin-top: 2rem; color: #444; }",
        (
            ".chart { background: white; border: 1px solid #ddd; "
            "border-radius: 8px; padding: 1rem; margin-bottom: 2rem; }"
        ),
        ".chart svg { width: 100%; height: auto; }",
        ".no-data { color: #999; font-style: italic; padding: 1rem; }",
        "</style>",
        "</head><body>",
        f"<h1>{escape(title)}</h1>",
    ]
    for heading, svg in sections:
        parts.append(f"<h2>{escape(heading)}</h2>")
        # Charts are generated by Matplotlib, which XML-escapes text labels.
        parts.append(f'<div class="chart">{svg}</div>')
    parts.append("</body></html>")
    return "\n".join(parts)


def _format_bytes(value: float) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if abs(value) < 1024:
            return f"{value:.1f} {unit}"
        value /= 1024
    return f"{value:.1f} PB"


def _format_bytes_tick(value: float, _position: int) -> str:
    return _format_bytes(value)


def _setup_axes(ax: Axes) -> None:
    ax.xaxis.set_major_formatter(DateFormatter("%H:%M"))
    ax.tick_params(axis="x", rotation=30)  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
    ax.grid(True, alpha=0.3)  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.


def plot_link_series(df: pl.DataFrame) -> Figure:
    fig, ax = plt.subplots(figsize=(10, 4))
    links = cast(list[object], df["link_name"].unique().to_list())
    for link in links:
        ldf = df.filter(pl.col("link_name") == link).sort("timestamp")
        if "bytes_rx" in ldf.columns:
            _ = ax.plot(ldf["timestamp"], ldf["bytes_rx"], label=f"{link} RX")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
        if "bytes_tx" in ldf.columns:
            _ = ax.plot(  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
                ldf["timestamp"], ldf["bytes_tx"], label=f"{link} TX", linestyle="--"
            )
    _ = ax.set_ylabel("Bytes")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
    ax.yaxis.set_major_formatter(FuncFormatter(_format_bytes_tick))
    _ = ax.legend(fontsize=8, loc="upper left")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
    _setup_axes(ax)
    fig.tight_layout()
    return fig


def plot_health_series(df: pl.DataFrame) -> Figure:
    fig, ax1 = plt.subplots(figsize=(10, 4))
    df = df.sort("timestamp")

    has_pct = False
    if "cpu_pct" in df.columns and df["cpu_pct"].is_not_null().any():
        _ = ax1.plot(df["timestamp"], df["cpu_pct"], label="CPU %", color="tab:red")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
        has_pct = True
    if "memory_pct" in df.columns and df["memory_pct"].is_not_null().any():
        _ = ax1.plot(df["timestamp"], df["memory_pct"], label="Memory %", color="tab:blue")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
        has_pct = True

    if has_pct:
        _ = ax1.set_ylabel("Percent")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
        _ = ax1.set_ylim(0, 100)
        _ = ax1.legend(fontsize=8, loc="upper left")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.

    if "flow_count" in df.columns and df["flow_count"].is_not_null().any():
        ax2 = ax1.twinx()  # pyright: ignore[reportUnknownMemberType]  # Matplotlib leaves axes class options open-ended.
        _ = ax2.plot(  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
            df["timestamp"],
            df["flow_count"],
            label="Flows",
            color="tab:green",
            alpha=0.7,
        )
        _ = ax2.set_ylabel("Flow Count")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
        _ = ax2.legend(fontsize=8, loc="upper right")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.

    _setup_axes(ax1)
    fig.tight_layout()
    return fig


def plot_flow_series(df: pl.DataFrame) -> Figure:
    fig, ax = plt.subplots(figsize=(10, 4))
    group_col = (
        "app"
        if "app" in df.columns
        else "application"
        if "application" in df.columns
        else None
    )
    if group_col is None:
        for col in df.columns:
            if col not in ("timestamp",):
                group_col = col
                break

    if group_col and group_col in df.columns:
        groups = cast(list[object], df[group_col].unique().to_list())
        for group in groups:
            gdf = df.filter(pl.col(group_col) == group).sort("timestamp")
            metric_col = (
                "total_bytes"
                if "total_bytes" in gdf.columns
                else "bytes_rx"
                if "bytes_rx" in gdf.columns
                else None
            )
            if metric_col:
                _ = ax.plot(gdf["timestamp"], gdf[metric_col], label=str(group))  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
    else:
        metric_cols = [c for c in df.columns if c != "timestamp"]
        for col in metric_cols:
            if df[col].is_not_null().any():
                _ = ax.plot(df["timestamp"], df[col], label=col)  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.

    _ = ax.set_ylabel("Bytes")  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
    ax.yaxis.set_major_formatter(FuncFormatter(_format_bytes_tick))
    _ = ax.legend(fontsize=7, loc="upper left", ncol=2)  # pyright: ignore[reportUnknownMemberType]  # Matplotlib exposes flexible style kwargs.
    _setup_axes(ax)
    fig.tight_layout()
    return fig


async def fetch_edge_series(
    analytics: Analytics,
    edge_id: int,
    edge_name: str,
    interval: ApiInterval,
) -> list[tuple[str, str]]:
    sections: list[tuple[str, str]] = []

    # Link throughput
    try:
        link_frame = await analytics.get_edge_link_series(edge_id, interval)
        df = link_frame.to_dataframe()
        if not df.is_empty():
            fig = plot_link_series(df)
            sections.append((f"Link Throughput — {edge_name}", svg_from_figure(fig)))
        else:
            sections.append(
                (f"Link Throughput — {edge_name}", '<p class="no-data">No data</p>')
            )
    except Exception as exc:  # noqa: BLE001 - preserve a partial report after endpoint failures
        logger.warning("Link series failed for %s (%s)", edge_name, type(exc).__name__)
        sections.append(
            (
                f"Link Throughput — {edge_name}",
                '<p class="no-data">Request failed; see the local log for details.</p>',
            )
        )

    # Health
    try:
        health_frame = await analytics.get_edge_health_series(edge_id, interval)
        df = health_frame.to_dataframe()
        if not df.is_empty():
            fig = plot_health_series(df)
            sections.append((f"Health — {edge_name}", svg_from_figure(fig)))
        else:
            sections.append((f"Health — {edge_name}", '<p class="no-data">No data</p>'))
    except Exception as exc:  # noqa: BLE001 - preserve a partial report after endpoint failures
        logger.warning(
            "Health series failed for %s (%s)", edge_name, type(exc).__name__
        )
        sections.append(
            (
                f"Health — {edge_name}",
                '<p class="no-data">Request failed; see the local log for details.</p>',
            )
        )

    # Flow by app (may require VIEW_FLOW_STATS privilege)
    try:
        flow_frame = await analytics.get_edge_flow_series(
            edge_id,
            interval,
            FlowGroupBy.APP,
            limit=10,
            sort=FlowMetric.TOTAL_BYTES,
        )
        df = flow_frame.to_dataframe()
        if not df.is_empty():
            fig = plot_flow_series(df)
            sections.append(
                (f"Flow by Application — {edge_name}", svg_from_figure(fig))
            )
        else:
            sections.append(
                (f"Flow by Application — {edge_name}", '<p class="no-data">No data</p>')
            )
    except Exception as exc:  # noqa: BLE001 - preserve a partial report after endpoint failures
        logger.warning("Flow series failed for %s (%s)", edge_name, type(exc).__name__)
        sections.append(
            (
                f"Flow by Application — {edge_name}",
                '<p class="no-data">Unavailable; check VIEW_FLOW_STATS access and the local log.</p>',
            )
        )

    return sections


async def main() -> None:
    args = parse_args()
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s | %(levelname)-8s | %(message)s",
        datefmt="%H:%M:%S",
    )

    vco_host, vco_token = get_vco_credentials(args.env)
    interval = make_interval(args.hours)

    async with VcoClient(vco_host, vco_token) as client:
        enterprise_id = args.enterprise_id
        if enterprise_id is None:
            ent = await client.get_enterprise(GetEnterprise())
            enterprise_id = ent.id_
            logger.info(
                "Auto-discovered enterprise: %s (ID %s)", ent.name, enterprise_id
            )

        logger.info("Fetching edges for enterprise %s...", enterprise_id)
        edges = await client.get_enterprise_edges(
            GetEnterpriseEdges(enterprise_id=enterprise_id)
        )

        connected = [e for e in edges if e.edge_state == EdgeState.CONNECTED]
        if args.edge_name is not None:
            connected = [
                e
                for e in connected
                if isinstance(e.name, str) and args.edge_name.lower() in e.name.lower()
            ]

        if not connected:
            logger.warning("No connected edges found matching criteria")
            return

        logger.info(
            "%d connected edge(s): %s",
            len(connected),
            ", ".join(e.name or f"edge-{e.id_}" for e in connected),
        )

        analytics = Analytics(client, enterprise_id=enterprise_id)
        all_sections: list[tuple[str, str]] = []

        for edge in connected:
            if not isinstance(edge.id_, int):
                continue
            edge_name = edge.name
            if not isinstance(edge_name, str) or not edge_name:
                edge_name = f"edge-{edge.id_}"
            logger.info("Fetching series for %s (ID %s)...", edge_name, edge.id_)
            sections = await fetch_edge_series(analytics, edge.id_, edge_name, interval)
            all_sections.extend(sections)

    if not all_sections:
        logger.warning("No chart data collected")
        return

    title = f"Analytics Report — Enterprise {enterprise_id} — Last {args.hours}h"
    html = build_html(all_sections, title)

    output = Path(args.output)
    _ = output.write_text(html)
    logger.info("Report written to %s", output.resolve())

    _ = webbrowser.open(output.resolve().as_uri())


if __name__ == "__main__":
    asyncio.run(main())
